#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';

const path = new URL('../src/main/resources/textmate/carve.tmLanguage.json', import.meta.url);
const original = readFileSync(path, 'utf8');
const grammar = JSON.parse(original);
const repository = grammar.repository;
const prefix = 'line-inline-';
for (const name of Object.keys(repository)) {
  if (name.startsWith(prefix)) delete repository[name];
}
const roots = ['raw-inline', 'inline-literal', 'inline-code', 'links', 'images',
  'footnotes', 'critic-markup', 'emphasis', 'heading-span-attributes', 'inline-comment',
  'math', 'cross-reference', 'autolink', 'extension-inline', 'include-directive',
  'mentions-tags', 'smart-typography', 'hard-break', 'trailing-comment'];
const includes = node => {
  const result = new Set();
  const visit = value => {
    if (!value || typeof value !== 'object') return;
    if (typeof value.include === 'string' && value.include.startsWith('#')) result.add(value.include.slice(1));
    Object.values(value).forEach(visit);
  };
  visit(node);
  return result;
};
const hasRegion = node => {
  if (!node || typeof node !== 'object') return false;
  return 'begin' in node || Object.values(node).some(hasRegion);
};
const reachable = new Set();
const visit = name => {
  if (reachable.has(name)) return;
  if (!repository[name]) throw new Error(`Unknown rule: ${name}`);
  reachable.add(name);
  includes(repository[name]).forEach(visit);
};
roots.forEach(visit);
const bounded = new Set([...reachable].filter(name => hasRegion(repository[name])));
let changed;
do {
  changed = false;
  for (const name of reachable) {
    if (!bounded.has(name) && [...includes(repository[name])].some(ref => bounded.has(ref))) {
      bounded.add(name);
      changed = true;
    }
  }
} while (changed);
const clone = node => {
  if (Array.isArray(node)) return node.map(clone);
  if (!node || typeof node !== 'object') return node;
  const copy = Object.fromEntries(Object.entries(node).filter(([key]) => key !== 'comment').map(([key, value]) => [key, clone(value)]));
  if (copy.include?.startsWith('#') && bounded.has(copy.include.slice(1))) copy.include = `#${prefix}${copy.include.slice(1)}`;
  if (copy.begin !== undefined) copy.end = `(?:${copy.end})|(?=$)`;
  return copy;
};
for (const name of [...bounded].sort()) repository[prefix + name] = clone(repository[name]);
repository['heading-inline'] = {
  comment: 'Inline regions in headings and captions end on the current line. Generated by tools/generate-line-inline.mjs from the shared inline rules.',
  patterns: roots.map(name => ({ include: `#${bounded.has(name) ? prefix : ''}${name}` })),
};
const positions = [...original.matchAll(/^    "([^"\n]+)": /gm)];
const repositoryEnd = original.lastIndexOf('\n  }');
const chunks = new Map(positions.map((match, i) => [match[1],
  original.slice(match.index, positions[i + 1]?.index ?? repositoryEnd).trimEnd().replace(/,$/, '')]));
const inputRepository = JSON.parse(original).repository;
const entries = Object.entries(repository).map(([name, node]) => {
  if (chunks.has(name) && JSON.stringify(inputRepository[name]) === JSON.stringify(node)) return chunks.get(name);
  return JSON.stringify({ [name]: node }, null, 2).slice(2, -2).split('\n').map(line => '  ' + line).join('\n');
});
const output = original.slice(0, positions[0].index) + entries.join(',\n') + original.slice(repositoryEnd);
if (process.argv.includes('--check')) {
  if (output !== original) throw new Error('Line inline rules are stale; run tools/generate-line-inline.mjs');
} else writeFileSync(path, output);
