package org.markupcarve.carve

import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File

/** Checks committed bundle headers and the pinned npm package metadata. */
class CarveBundleProvenanceTest {

    private val sha = Regex("^[0-9a-f]{40}$")

    @Test
    fun previewBundleRecordsTheCarveJsCommitItWasBuiltFrom() {
        val header = headerOf(resource("js/carve.iife.js"))

        assertTrue(
            "carve.iife.js has lost its generator line - rebuild it with " +
                "tools/build-carve-bundle.sh:\n$header",
            header.any { it.contains("Generated by tools/build-carve-bundle.sh") },
        )

        val commit = capture(header, Regex("Bundled from markup-carve/carve-js commit (\\S+)"))
            ?: throw AssertionError(
                "carve.iife.js records no carve-js commit. The header is written by " +
                    "tools/build-carve-bundle.sh; rebuild rather than hand-editing:\n$header",
            )
        assertTrue(
            "carve.iife.js records '$commit' as its carve-js commit, which is not a 40-character " +
                "sha. A placeholder here is exactly the unreadable provenance this test exists " +
                "to reject.",
            sha.matches(commit),
        )
        assertTrue(
            "carve.iife.js records no build timestamp:\n$header",
            capture(header, BUILT_AT) != null,
        )
    }

    @Test
    fun languageServerBundleRecordsBothItsOwnCommitAndTheEngineItCarries() {
        val header = headerOf(resource("lsp/server.js"))

        val lspCommit = capture(header, Regex("Bundled from markup-carve/carve-lsp commit (\\S+)"))
            ?: throw AssertionError("lsp/server.js records no carve-lsp commit:\n$header")
        assertTrue(
            "lsp/server.js records '$lspCommit' as its carve-lsp commit, which is not a 40-character sha.",
            sha.matches(lspCommit),
        )

        // Two legitimate shapes, because carve-lsp has used both: a git
        // dependency (`commit <sha>`) and, since it pinned the engine exactly,
        // a published one (`npm <version>`). Anything else - and in particular
        // the literal `unknown` this field used to degrade to - is a failure.
        val engine = capture(header, Regex("carve-js dependency (.+)"))?.trim()
            ?: throw AssertionError("lsp/server.js records no carve-js dependency:\n$header")
        assertTrue(
            "lsp/server.js records its carve-js dependency as '$engine'. It must be " +
                "'commit <40-hex>' or 'npm <version>' - a placeholder means the build script's " +
                "lockfile probe stopped matching and the provenance is no longer readable.",
            ENGINE_REF.matches(engine),
        )
    }

    /** Both npm packages must name published releases in the server header. */
    @Test
    fun bothVendoredHalvesNameTheReleaseTheyWereBuiltFrom() {
        val header = headerOf(resource("lsp/server.js"))

        for ((field, what) in listOf(
            "carve-lsp release" to "the language server itself",
            "carve-js release" to "the engine it carries",
        )) {
            val release = capture(header, Regex("$field (.+)"))?.trim()
                ?: throw AssertionError(
                    "lsp/server.js records no '$field'. tools/build-lsp-bundle.sh writes it; " +
                        "rebuild rather than hand-editing:\n$header",
                )
            assertTrue(
                "lsp/server.js names '$release' as the release of $what. A vendored bundle has " +
                    "to come from a published release. Rebuild from the npm pin.",
                RELEASE_REF.matches(release),
            )
        }
    }

    /** The preview and server must carry the same published carve-js commit. */
    @Test
    fun bothBundlesCarryTheSameCarveJsCommit() {
        val previewHeader = headerOf(resource("js/carve.iife.js"))
        val serverHeader = headerOf(resource("lsp/server.js"))

        val preview = capture(previewHeader, Regex("Bundled from markup-carve/carve-js commit (\\S+)"))
            ?: throw AssertionError("carve.iife.js records no carve-js commit:\n$previewHeader")
        val engine = capture(serverHeader, Regex("carve-js dependency (.+)"))?.trim()
            ?: throw AssertionError("lsp/server.js records no carve-js dependency:\n$serverHeader")

        // A commit is required to compare the server with the preview bundle.
        val server = capture(listOf(engine), Regex("^commit ([0-9a-f]{40})$"))
            ?: throw AssertionError(
                "lsp/server.js carries carve-js as '$engine', which cannot be compared against the " +
                    "preview bundle's commit $preview. Rebuild it with tools/build-lsp-bundle.sh, " +
                    "which stamps the npm gitHead of the pinned carve-js.",
            )

        assertEquals(
            "The two vendored engines are different builds of carve-js: the preview pane runs " +
                "$preview and the language server carries $server. They render the same document " +
                "for the same user, so they have to be one revision. Rebuild both with " +
                "'tools/bump-lsp-bundle.sh <lsp-version> <carve-version>' with matching releases.",
            preview,
            server,
        )
    }

    @Test
    fun theVersionFileAgreesWithTheBundleItWasWrittenBeside() {
        val header = headerOf(resource("lsp/server.js"))
        val version = resource("lsp/VERSION").readLines().filter { it.isNotBlank() }

        val fromVersion = version.associate { line ->
            val (key, value) = line.split(' ', limit = 2).let { it[0] to it.getOrElse(1) { "" } }
            key to value.trim()
        }

        assertEquals(
            "lsp/VERSION names a different carve-lsp commit than the header inside " +
                "lsp/server.js. They are written by the same run of " +
                "tools/build-lsp-bundle.sh, so disagreeing means one of the two was " +
                "regenerated or edited alone.",
            capture(header, Regex("Bundled from markup-carve/carve-lsp commit (\\S+)")),
            fromVersion["carve-lsp"],
        )
        assertEquals(
            "lsp/VERSION names a different carve-js dependency than the header inside " +
                "lsp/server.js.",
            capture(header, Regex("carve-js dependency (.+)"))?.trim(),
            fromVersion["carve-js"],
        )
        assertEquals(
            "lsp/VERSION names a different carve-lsp release than the header inside " +
                "lsp/server.js.",
            capture(header, Regex("carve-lsp release (.+)"))?.trim(),
            fromVersion["carve-lsp-release"],
        )
        assertEquals(
            "lsp/VERSION names a different carve-js release than the header inside " +
                "lsp/server.js.",
            capture(header, Regex("carve-js release (.+)"))?.trim(),
            fromVersion["carve-js-release"],
        )
    }

    @Test
    fun theBundledServerIsThePinnedNpmVersion() {
        val pin = sourceFile("tools/lsp-bundle/package.json").readText()
        val lock = sourceFile("tools/lsp-bundle/package-lock.json").readText()
        val header = headerOf(resource("lsp/server.js"))
        val lspVersion = Regex(""""@markup-carve/carve-lsp"\s*:\s*"([^"]+)"""")
            .find(pin)?.groupValues?.get(1) ?: throw AssertionError("Missing carve-lsp pin")
        val carveVersion = Regex(""""@markup-carve/carve"\s*:\s*"([^"]+)"""")
            .find(pin)?.groupValues?.get(1) ?: throw AssertionError("Missing carve-js override")
        assertTrue("carve-lsp pin must be exact", Regex("\\d+\\.\\d+\\.\\d+").matches(lspVersion))
        assertTrue("carve-js override must be exact", Regex("\\d+\\.\\d+\\.\\d+").matches(carveVersion))
        assertEquals("v$lspVersion", capture(header, Regex("carve-lsp release (.+)"))?.trim())
        assertEquals(carveVersion, capture(header, Regex("carve-js release (.+)"))?.trim())
        val locked = Regex(""""node_modules/@markup-carve/carve-lsp"\s*:\s*\{[^}]*"version"\s*:\s*"([^"]+)"""", RegexOption.DOT_MATCHES_ALL)
            .find(lock)?.groupValues?.get(1)
        assertEquals(lspVersion, locked)
    }

    /** The leading comment block, which is all the provenance ever occupies. */
    private fun headerOf(file: File): List<String> =
        file.useLines { lines -> lines.take(12).takeWhile { it.startsWith("//") || it.isBlank() }.toList() }

    private fun capture(header: List<String>, pattern: Regex): String? =
        header.firstNotNullOfOrNull { pattern.find(it)?.groupValues?.get(1) }

    private fun resource(relative: String): File {
        return sourceFile("src/main/resources/$relative")
    }

    private fun sourceFile(relative: String): File {
        var dir: File? = File(System.getProperty("user.dir")).absoluteFile
        while (dir != null) {
            val candidate = File(dir, relative)
            if (candidate.isFile) return candidate
            dir = dir.parentFile
        }
        throw AssertionError("$relative not found from ${System.getProperty("user.dir")}")
    }

    private companion object {
        val BUILT_AT = Regex("Built \\(UTC\\): (\\S+)")
        val ENGINE_REF = Regex("^(commit [0-9a-f]{40}|npm \\d+\\.\\d+\\.\\d+\\S*)$")
        /** A release tag, in either spelling the org uses: `v0.1.4` and `0.1.5`. */
        val RELEASE_REF = Regex("^v?\\d+\\.\\d+\\.\\d+\\S*$")
    }
}
